import { test, expect } from '@playwright/test';
import { securityLogin } from './security-login.js';

test('designer board and admin retention work through the real API', async ({ page, request }) => {
  const seed = await request.post('http://127.0.0.1:5078/__test__/kanban-fixtures');
  expect(seed.ok()).toBeTruthy();
  await page.addInitScript(() => localStorage.setItem('tinzel_language', 'en'));
  await securityLogin(page.request, 'designer');
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1500, height: 1000 });
  await page.goto('/staff/design');
  const board = page.locator('.designer-kanban');
  await expect(board.getByRole('heading', {name:'New design orders',exact:true})).toBeVisible();
  const manager = page.getByRole('region', {name:'Returned by managers',exact:true});
  const client = page.getByRole('region', {name:'Returned by client',exact:true});
  const completed = page.getByRole('region', {name:'Completed',exact:true});
  await expect(manager.getByRole('button', {name:'Open TNZ-BOARD-MANAGER'})).toBeVisible();
  await expect(client.getByRole('button', {name:'Open TNZ-BOARD-CLIENT'})).toBeVisible();
  await expect(completed.getByRole('button', {name:'Open TNZ-BOARD-DONE'})).toBeVisible();
  const fresh = page.getByRole('region', {name:'New design orders',exact:true});
  await expect(fresh.locator('.designer-kanban-card')).toHaveCount(10);
  await fresh.getByRole('button', {name:'Next page',exact:true}).click();
  await expect(fresh.locator('.designer-kanban-pagination')).toContainText('Page 2');
  await expect(fresh.locator('.designer-kanban-card')).toHaveCount(3);
  await page.getByRole('searchbox', {name:'Search orders'}).fill('TNZ-BOARD-NEW-00');
  await expect(fresh.locator('.designer-kanban-card')).toHaveCount(1);
  await expect(fresh.getByRole('button', {name:'Open TNZ-BOARD-NEW-00'})).toBeVisible();
  await expect(client.getByRole('heading', { name: 'No matching orders', exact: true })).toBeVisible();
  await page.getByRole('searchbox').clear();
  await expect(fresh.locator('.designer-kanban-card')).toHaveCount(10);
  await page.screenshot({path:'/tmp/tinzel-designer-kanban-desktop.png',fullPage:true});
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({path:'/tmp/tinzel-designer-kanban-mobile.png',fullPage:true});
  await client.getByRole('button', {name:'Open TNZ-BOARD-CLIENT'}).click();
  await expect(page).toHaveURL(/\/staff\/design\/orders\//);
  await expect(page.getByRole('heading',{name:'TNZ-BOARD-CLIENT',exact:true})).toBeVisible();
  // Admin setting persists and controls cleanup of the same fixture seen in the board.
  await page.context().clearCookies();
  await securityLogin(page.request, 'admin');
  await page.goto('/staff/system');
  await page.getByRole('button', { name: 'Magazine history', exact: true }).click();
  const retention = page.getByLabel('Keep completed submissions for (days)');
  await expect(retention).toHaveValue('7');
  await retention.fill('30');
  await page.getByRole('button', {name:'Save retention period',exact:true}).click();
  await expect(page.getByText('Retention period saved.',{exact:true})).toBeVisible();
  expect((await (await request.post('http://127.0.0.1:5078/__test__/retention-run')).json()).deleted).toBe(0);
  await page.reload(); await expect(retention).toHaveValue('30');
  await retention.fill('7');
  await page.getByRole('button', {name:'Save retention period',exact:true}).click();
  await expect(page.getByText('Retention period saved.',{exact:true})).toBeVisible();
  expect((await (await request.post('http://127.0.0.1:5078/__test__/retention-run')).json()).deleted).toBe(1);
  await page.context().clearCookies();
  await securityLogin(page.request, 'designer');
  await page.goto('/staff/design');
  await expect(completed.getByRole('button', {name:'Open TNZ-BOARD-DONE'})).toHaveCount(0);
  await expect(manager.getByRole('button', {name:'Open TNZ-BOARD-MANAGER'})).toBeVisible();
  const forbidden = await page.request.get('/api/admin/config');
  expect(forbidden.status()).toBe(403);
  expect(errors).toEqual([]);
});
