import { test, expect } from '@playwright/test';
import { securityLogin } from './security-login.js';

test('admin payment options persist and appear after submission in both languages on mobile', async ({ page }) => {
  page.setDefaultTimeout(15000);
  await page.addInitScript(() => localStorage.setItem('tinzel_language', 'en'));
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await securityLogin(page.request, 'admin');
  await page.goto('/staff/system');
  await page.getByRole('button', { name: 'Payment settings', exact: true }).click();
  const settings = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Payment options', exact: true }) });
  await expect(settings).toBeVisible();
  for (const [index, type, name, number] of [[0, 'mobile', 'Test Mobile', 'TEST-MOBILE'], [1, 'bank', 'Test Bank', 'TEST-BANK'], [2, 'till', 'Hidden Till', 'TEST-HIDDEN']]) {
    await settings.getByRole('button', { name: 'Add payment option', exact: true }).click();
    const option = settings.getByRole('group', { name: `Payment option ${index + 1}`, exact: true });
    await option.getByLabel('Payment type', { exact: true }).selectOption(type);
    await option.getByLabel('Provider / bank name', { exact: true }).fill(name);
    await option.getByLabel('Display name in Kiswahili (optional)', { exact: true }).fill(`Kiswahili ${name}`);
    await option.getByLabel('Till / phone / account number', { exact: true }).fill(number);
    await option.getByLabel('Account name', { exact: true }).fill('Test recipient');
    await option.getByLabel('Payment instructions', { exact: true }).fill(`Test only.\nInstructions for ${name}.`);
    await option.getByLabel('Instructions in Kiswahili (optional)', { exact: true }).fill(`Majaribio pekee: ${name}.`);
  }
  await settings.getByRole('group', { name: 'Payment option 3', exact: true }).getByLabel('Show to customers').uncheck();
  await settings.getByRole('group', { name: 'Payment option 2', exact: true }).getByRole('button', { name: 'Move up', exact: true }).click();
  await settings.getByRole('button', { name: 'Save payment options', exact: true }).click();
  await expect(settings.getByText('Payment options saved.', { exact: true })).toBeVisible();
  await page.reload();
  await expect(settings.getByRole('group', { name: 'Payment option 1', exact: true }).getByLabel('Provider / bank name', { exact: true })).toHaveValue('Test Bank');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await settings.screenshot({ path: '/tmp/tinzel-payment-options-admin.png' });
  await page.goto('/catalogue/upload-performance-test?step=photos');
  await expect(page.locator('#upload-first')).toBeAttached();
  await page.getByRole('button', { name: '1 Your details', exact: true }).click();
  await page.locator('#magazine-client-name').pressSequentially('Payment browser fixture');
  await page.getByPlaceholder('e.g. +255712345678').pressSequentially('+255700000001');
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('tinzel:answers:v2:upload-performance-test') || '{}')?.data?.clientWhatsApp)).toBeTruthy();
  await page.getByRole('button', { name: '4 Review', exact: true }).click();
  await page.getByRole('button', { name: /Continue.*Pay/i }).click();
  const payment = page.locator('.payment-page');
  await expect(payment.getByRole('heading', { name: 'Ways to pay', exact: true })).toBeVisible();
  await expect(payment.getByRole('combobox', { name: 'Payment method', exact: true }).locator('option')).toHaveText(['Test Bank', 'Test Mobile']);
  await expect(payment.locator('article h3')).toHaveText(['Test Bank']);
  await payment.getByRole('combobox', { name: 'Payment method', exact: true }).selectOption({ label: 'Test Mobile' });
  await expect(payment).toContainText('TEST-MOBILE');
  await expect(payment).not.toContainText('TEST-BANK');
  await payment.getByRole('combobox', { name: 'Payment method', exact: true }).selectOption({ label: 'Test Bank' });
  await expect(payment).not.toContainText('TEST-HIDDEN');
  await expect(payment).not.toContainText('Do not pay this test order.');
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  await payment.getByRole('button', { name: 'Copy Test Bank', exact: true }).click();
  await expect(payment.getByRole('button', { name: 'Copy Test Bank', exact: true })).toContainText('Copied');
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('TEST-BANK');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await payment.screenshot({ path: '/tmp/tinzel-payment-options-customer.png' });
  await page.getByRole('button', { name: 'SW', exact: true }).click();
  await expect(payment.getByRole('combobox', { name: 'Njia ya malipo', exact: true }).locator('option')).toHaveText(['Kiswahili Test Bank', 'Kiswahili Test Mobile']);
  await expect(payment.locator('article h3')).toHaveText(['Kiswahili Test Bank']);
  await expect(payment).toContainText('Majaribio pekee: Test Bank.');
  await page.getByRole('button', { name: 'EN', exact: true }).click();
  await page.goto('/staff/system');
  await page.getByRole('button', { name: 'Payment settings', exact: true }).click();
  for (let i = 0; i < 3; i++) await settings.getByRole('button', { name: 'Remove option', exact: true }).first().click();
  await settings.getByRole('button', { name: 'Save payment options', exact: true }).click();
  await expect(settings.getByText('Payment options saved.', { exact: true })).toBeVisible();
  await page.goto('/catalogue/upload-performance-test?step=photos');
  await expect(page.locator('#upload-first')).toBeAttached();
  await page.getByRole('button', { name: '1 Your details', exact: true }).click();
  await page.locator('#magazine-client-name').pressSequentially('No payment options fixture');
  await page.getByPlaceholder('e.g. +255712345678').pressSequentially('+255700000002');
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('tinzel:answers:v2:upload-performance-test') || '{}')?.data?.clientWhatsApp)).toBeTruthy();
  await page.getByRole('button', { name: '4 Review', exact: true }).click();
  await page.getByRole('button', { name: /Continue.*Pay/i }).click();
  await expect(payment).toContainText('Payment details are currently unavailable.');
  await expect(payment.locator('article')).toHaveCount(0);
  expect(errors).toEqual([]);
});
