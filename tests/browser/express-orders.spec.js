test('express flows from uploaded photo and review through payment to manager and designer priority', async ({ page }) => {
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem('tinzel_language', 'en'));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/catalogue/upload-performance-test?step=details');
  await page.locator('#magazine-client-name').fill('Express browser fixture');
  await page.getByPlaceholder('e.g. +255712345678').fill('+255700000041');
  await page.getByRole('button', { name: '3 Photographs', exact: true }).click();
  await page.locator('#upload-first').setInputFiles({ name: 'express-photo.png', mimeType: 'image/png', buffer: pixels });
  await expect(page.locator('[data-field-id=first] .photo-field__tile')).toHaveCount(1);
  await page.getByRole('button', { name: '4 Review', exact: true }).click();
  const choice = page.locator('.express-choice');
  await expect(choice.getByRole('radio', { name: /Standard order/ })).toBeChecked();
  await expect(choice.locator('.express-price-breakdown > div').last()).toContainText('50,000');
  await choice.getByRole('radio', { name: /Express/ }).check();
  await expect(choice.locator('.express-price-breakdown > div').last()).toContainText('70,000');
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('tinzel:answers:v2:upload-performance-test') || '{}')?.data?.isExpress)).toBe(true);
  await page.reload();
  await expect(choice.getByRole('radio', { name: /Express/ })).toBeChecked();
  await page.getByRole('button', { name: 'SW', exact: true }).click();
  await expect(choice).toContainText('Jumapili haihesabiwi');
  await page.getByRole('button', { name: 'EN', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await choice.screenshot({ path: '/tmp/tinzel-express-choice-mobile.png' });
  const submitted = page.waitForResponse(response => /\/sessions\/[^/]+\/submit$/.test(new URL(response.url()).pathname));
  await page.getByRole('button', { name: /Continue.*Pay/i }).click();
  const result = await (await submitted).json();
  expect(result.order.price).toBe(70000);
  expect(result.order.isExpress).toBe(true);
  expect(result.order.photosCount).toBe(1);
  const payment = page.locator('.payment-page');
  await expect(payment).toContainText('70,000');
  await expect(payment.locator('.express-order')).toContainText('Awaiting payment');
  await payment.screenshot({ path: '/tmp/tinzel-express-payment-mobile.png' });
  // A newer standard order must still appear below this express order.
  const standard = await page.request.post('/api/public/forms/upload-performance-test/submit', { data: { clientName: 'Standard browser fixture', clientWhatsApp: '+255700000042', answers: {}, isExpress: false } });
  expect(standard.status()).toBe(201);
  await securityLogin(page.request, 'manager');
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goto('/staff/pre-design');
  const first = page.locator('.manager-stage-row').first();
  await expect(first).toContainText('Express browser fixture');
  await expect(first.locator('.express-order')).toContainText('Awaiting payment');
  await first.click();
  await page.getByRole('button', { name: 'Verify payment', exact: true }).last().click();
  const dialog = page.locator('.manager-action-modal');
  await expect(dialog.getByLabel('Amount paid (TZS)', { exact: true })).toHaveValue('70000');
  await dialog.getByLabel('Payment reference', { exact: true }).fill('EXPRESS-BROWSER-TEST');
  const verified = page.waitForResponse(response => response.url().includes('/verify-payment') && response.request().method() === 'POST');
  await dialog.locator('button[type=submit]').click();
  const paid = await (await verified).json();
  expect(paid.success).toBe(true);
  expect(paid.order.expressStartedAt).toBeTruthy();
  expect(paid.order.expressDueAt).toBeTruthy();
  await page.goto('/staff/design-phase');
  await expect(page.locator('.manager-stage-row').filter({ hasText: 'Express browser fixture' }).locator('.express-order')).toContainText('24h 00m left');
  await page.screenshot({ path: '/tmp/tinzel-express-manager-desktop.png', fullPage: true });
  await page.getByRole('button', { name: /Priority Queue/ }).click();
  await expect(page.locator('.manager-attention-table tbody tr').first()).toContainText('Express browser fixture');
  await expect(page.locator('.manager-attention-table tbody tr').first().locator('.express-order')).toContainText('24h 00m left');
  await page.context().clearCookies();
  await securityLogin(page.request, 'designer');
  await page.goto('/staff/design');
  const newOrders = page.getByRole('region', { name: 'New design orders', exact: true });
  await expect(newOrders.locator('.designer-kanban-card').first()).toContainText('Express browser fixture');
  await expect(newOrders.locator('.designer-kanban-card').first().locator('.express-order')).toContainText('24h 00m left');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await newOrders.screenshot({ path: '/tmp/tinzel-express-designer-mobile.png' });
  const alerts = await (await page.request.get('/api/notifications/history')).json();
  expect(JSON.stringify(alerts)).toContain('EXPRESS');
  expect(errors).toEqual([]);
});
