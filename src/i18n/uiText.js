export function translateUI(text, lang) {
  if (lang !== 'sw' || typeof text !== 'string') return text;
  const key = text.trim();
  const translated = uiText[key] || folded[key.toLocaleLowerCase()];
  if (translated) return text.replace(key, translated);
  const counted = key.match(/^(.+?)(\s*\(\d+\))$/);
  if (counted) {
    const base = uiText[counted[1]] || folded[counted[1].toLocaleLowerCase()];
    if (base) return base + counted[2];
  }
  const versioned = key.match(/^(Draft version|Review complete draft V|Open version|Page reference|Fix)\s*(\d+)$/);
  if (versioned) {
    const base = uiText[versioned[1]] || folded[versioned[1].toLocaleLowerCase()];
    if (base) return base + ' ' + versioned[2];
  }
  return text;
}
